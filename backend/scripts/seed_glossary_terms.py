# DB에 쓰기 전에 데이터 실수를 잡는다: 허용되지 않은 난이도·카테고리, 중복 용어,
# 사전에 없는 용어를 가리키는 연관 태그(프런트에서 태그를 눌러도 검색 결과가 비게 된다)
def validate_seed_terms(rows: list[dict]) -> list[str]:
    errors: list[str] = []
    names = [row["term"] for row in rows]
    known = set(names)

    for name in sorted({name for name in names if names.count(name) > 1}):
        errors.append(f"중복 용어: {name}")

    related_by_term = {
        row["term"]: set(glossary_term_service.parse_related_terms(row.get("related_terms"))) for row in rows
    }

    for row in rows:
        if row["difficulty"] not in DIFFICULTIES:
            errors.append(f"{row['term']}: 알 수 없는 difficulty '{row['difficulty']}'")
        if row.get("category") not in CATEGORIES:
            errors.append(f"{row['term']}: 알 수 없는 category '{row.get('category')}'")
        for related in glossary_term_service.parse_related_terms(row.get("related_terms")):
            if related not in known:
                errors.append(f"{row['term']}: 연관 태그 '{related}'가 사전에 없음")
            elif related == row["term"]:
                errors.append(f"{row['term']}: 연관 태그에 자기 자신이 있음")
            # 연관 태그는 양방향이어야 한다 (A의 태그에 B가 있으면 B의 태그에도 A가 있어야 한다)
            elif row["term"] not in related_by_term[related]:
                errors.append(f"{row['term']}: '{related}'의 연관 태그에 '{row['term']}'가 없음 (한쪽만 연결됨)")

    return errors


async def main() -> None:
    errors = validate_seed_terms(SEED_TERMS)
    if errors:
        print("=== 시딩 데이터 오류 - DB에 쓰지 않았다 ===")
        for error in errors:
            print(f"  {error}")
        raise SystemExit(1)

    terms = await glossary_term_service.upsert_terms(SEED_TERMS)
    print(f"=== glossary_term: {len(terms)}건 upsert ===")
    for term in terms:
        print(f"  {term.id} | {term.term} ({term.difficulty} / {term.category})")


if __name__ == "__main__":
    asyncio.run(main())
